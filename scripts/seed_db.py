#!/usr/bin/env python3
"""Load the JSON seeds into a database.

Two outputs, either or both:

  --sqlite    build data/processed/scoutfox.db from db/schema.sqlite.sql
              (no server required -- this is the fastest way to poke at the
              seed data with SQL)
  --sql       write db/seed.sql, a plain INSERT script for PostgreSQL:

                  psql "$DATABASE_URL" -f db/schema.sql
                  psql "$DATABASE_URL" -f db/seed.sql

With no flags, both are produced.
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path
from typing import Any, Dict, List

sys.path.insert(0, str(Path(__file__).resolve().parent))

from seedlib import (  # noqa: E402
    DB_DIR,
    PROCESSED_DIR,
    SCHEMA_SQL,
    SEED_SQL,
    SQLITE_DB,
    SeedValidationError,
    load_all,
    validate_or_raise,
)

SQLITE_SCHEMA = DB_DIR / "schema.sqlite.sql"

# table -> (column, ...). Order matters: parents before children so the
# foreign keys resolve on insert.
TABLES: List[tuple] = [
    ("activities", ("id", "name", "type", "category", "city", "state",
                    "indoor_or_outdoor", "price_tier", "min_age", "max_age",
                    "avg_duration_hours", "rating", "tags", "description")),
    ("families", ("family_id", "name", "members", "budget_range", "home_location")),
    ("global_patterns", ("pattern_id", "cluster_name", "top_destinations",
                         "seasonal_preferences", "notes")),
    ("users", ("api_key", "display_name", "email", "tier", "points",
               "home_state", "family_id")),
    ("trips", ("trip_id", "family_id", "destination", "start_date", "end_date", "itinerary")),
    ("feedback", ("feedback_id", "trip_id", "family_id", "rating", "comments")),
    ("points_ledger", ("entry_id", "api_key", "event", "points", "activity_id",
                       "created_at", "note")),
]

# Seed file name for each table, where it differs from the table name.
SEED_FOR_TABLE = {"activities": "activities", "families": "families",
                  "global_patterns": "global_patterns", "users": "users",
                  "trips": "trips", "feedback": "feedback",
                  "points_ledger": "points_ledger"}

# Columns stored as JSON documents.
JSON_COLUMNS = {"tags", "members", "itinerary", "top_destinations", "seasonal_preferences"}


def _cell(column: str, value: Any) -> Any:
    """Normalise one seed value into something a driver will accept."""
    if column in JSON_COLUMNS:
        return json.dumps(value, ensure_ascii=False)
    return value


def _rows_for(table: str, seeds: Dict[str, List[Dict[str, Any]]], columns: tuple) -> List[tuple]:
    records = seeds[SEED_FOR_TABLE[table]]
    return [tuple(_cell(col, record.get(col)) for col in columns) for record in records]


def build_sqlite(seeds: Dict[str, List[Dict[str, Any]]]) -> Path:
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    if SQLITE_DB.exists():
        SQLITE_DB.unlink()

    connection = sqlite3.connect(SQLITE_DB)
    try:
        connection.executescript(SQLITE_SCHEMA.read_text(encoding="utf-8"))
        connection.execute("PRAGMA foreign_keys = ON")
        for table, columns in TABLES:
            rows = _rows_for(table, seeds, columns)
            placeholders = ", ".join("?" for _ in columns)
            statement = (
                f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({placeholders})"
            )
            connection.executemany(statement, rows)
            print(f"  {table:<16} {len(rows):>4} rows")
        connection.commit()
    finally:
        connection.close()
    return SQLITE_DB


def _sql_literal(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def build_sql(seeds: Dict[str, List[Dict[str, Any]]]) -> Path:
    DB_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        "-- Generated by scripts/seed_db.py -- do not edit by hand.",
        "-- Edit data/seeds/*.json and re-run:  python scripts/seed_db.py --sql",
        "--",
        f"-- Apply after {SCHEMA_SQL.relative_to(SCHEMA_SQL.parents[1])}:",
        '--   psql "$DATABASE_URL" -f db/schema.sql',
        '--   psql "$DATABASE_URL" -f db/seed.sql',
        "",
        "BEGIN;",
        "",
    ]

    for table, columns in TABLES:
        rows = _rows_for(table, seeds, columns)
        lines.append(f"-- {table} ({len(rows)} rows)")
        if not rows:
            lines.append("")
            continue
        lines.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES")
        rendered = [f"  ({', '.join(_sql_literal(cell) for cell in row)})" for row in rows]
        lines.append(",\n".join(rendered) + ";")
        lines.append("")
        print(f"  {table:<16} {len(rows):>4} rows")

    lines.append("COMMIT;")
    SEED_SQL.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return SEED_SQL


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sqlite", action="store_true", help="build the SQLite database")
    parser.add_argument("--sql", action="store_true", help="write db/seed.sql for PostgreSQL")
    args = parser.parse_args()

    want_sqlite = args.sqlite or not (args.sqlite or args.sql)
    want_sql = args.sql or not (args.sqlite or args.sql)

    try:
        seeds = load_all()
        validate_or_raise(seeds)
    except SeedValidationError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if want_sqlite:
        print("building SQLite database")
        path = build_sqlite(seeds)
        print(f"  -> {path}")
    if want_sql:
        print("writing PostgreSQL seed script")
        path = build_sql(seeds)
        print(f"  -> {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
